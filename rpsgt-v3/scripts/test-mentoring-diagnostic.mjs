import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const engine=require('../core/mentoring-diagnostic-engine.js');
const catalog=JSON.parse(fs.readFileSync(new URL('../data/mentoring/diagnostic-v1.json',import.meta.url),'utf8'));
const validation=engine.validateCatalog(catalog);
assert.equal(validation.valid,true,JSON.stringify(validation.issues));
assert.equal(validation.questionCount,24);
assert.equal(validation.sectionCount,4);
const perfect={};catalog.questions.forEach(q=>perfect[q.id]=q.answer);
const perfectResult=engine.grade(catalog,perfect,'2026-08-09T10:00:00Z');
assert.equal(perfectResult.correct,24);
assert.equal(perfectResult.targetMet,true);
assert.equal(engine.band(perfectResult).id,'application-ready');
const misses={...perfect};
['md-calc-01','md-calc-02','md-art-01','md-art-02','md-score-01','md-int-01'].forEach(id=>misses[id]=(catalog.questions.find(q=>q.id===id).answer+1)%4);
const result=engine.grade(catalog,misses,'2026-08-09T10:05:00Z');
assert.equal(result.correct,18);
assert.equal(result.targetMet,false);
assert.equal(engine.band(result).id,'targeted-reinforcement');
const plan=engine.mentoringPlan(catalog,result);
assert.ok(plan.priorities.length>=1);
let labs={};labs=engine.start(labs,'2026-08-09T09:00:00Z');
labs=engine.applyResult(labs,result);
let summary=engine.summary(labs);
assert.equal(summary.attempts,1);
assert.equal(summary.completed,false);
labs=engine.applyResult(labs,perfectResult);
summary=engine.summary(labs);
assert.equal(summary.attempts,2);
assert.equal(summary.completed,true);
assert.equal(summary.bestPercent,100);
console.log('Mentoring diagnostic validation passed:',{questions:validation.questionCount,sections:validation.sectionCount,perfect:perfectResult.percent,remediation:result.percent});
