import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const source=await readFile(join(root,'core/visual-psg-renderer.js'),'utf8');
const pack=JSON.parse(await readFile(join(root,'data/visual/prototype-sleep-staging.json'),'utf8'));
const sandbox={globalThis:{},window:{devicePixelRatio:1}};vm.createContext(sandbox);vm.runInContext(source,sandbox);
const renderer=sandbox.globalThis.RPSGTVisualPSGRenderer;
const labels=[];const context=new Proxy({fillText:text=>labels.push(text)},{get:(obj,key)=>obj[key]||(()=>{})});
const canvas={style:{},parentElement:{clientWidth:320},getContext:()=>context};
let metrics=renderer.render(canvas,pack.studies[0]);assert.equal(metrics.width,980);assert.equal(metrics.labelWidth,112);assert.equal(metrics.rowHeight,58);
labels.length=0;metrics=renderer.render(canvas,pack.studies[0],{width:218,fitWidth:true,hideLabels:true,rowHeight:30});
assert.equal(metrics.width,218);assert.equal(metrics.plotRight,218);assert.equal(metrics.labelWidth,0);assert.equal(metrics.rowHeight,30);
assert.equal(metrics.height,60+pack.studies[0].channels.length*30);
for(const channel of pack.studies[0].channels)assert.ok(!labels.includes(channel.label),'Pinned labels must not be repeated inside moving canvases');
assert.equal(renderer.hitTest(metrics,109,49).time,15);
console.log('PASS: default montage preserved; narrow viewport renders the full 30-second timebase without repeated channel labels.');
